package main

import "fmt"

func main() {
	var name string = "golang"
	var name2 = "goland"
	fmt.Println(name)
	fmt.Println(name2)

	var isAge = true
	fmt.Println(isAge)

	var age int = 10
	fmt.Println(age)

	var number float32 = 30.6
	fmt.Println(number)

	// short hand syntax
	language := "golang"
	fmt.Println(language)

	price := 350.5

	fmt.Println(price)
}
